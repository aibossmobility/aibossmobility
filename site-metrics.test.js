"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const os=require("node:os");
const path=require("node:path");
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"ai-boss-traffic-"));
process.env.RAILWAY_VOLUME_MOUNT_PATH=tmp;
const m=require("./site-metrics");
assert.equal(m.classifySource("linkedin",""),"social");
assert.equal(m.classifySource("","https://www.google.com/search?q=x"),"search");
assert.equal(m.classifySource("","https://ai.bossmobilelifecoach.com/page"),"internal");
assert.equal(m.classifySource("",""),"direct_or_unknown");
assert.equal(m.cleanPage("/meet-brian.html"),"/meet-brian");
assert.equal(m.cleanPage("/private-report"),null);
const html="<html><body><main>OK</main></body></html>";
assert.ok(m.inject(html,"/meet-brian","ai.bossmobilelifecoach.com").includes("site-traffic-client.js"));
assert.equal(m.inject(html,"/private-report","ai.bossmobilelifecoach.com"),html);
assert.equal(m.inject(html,"/meet-brian","bossmobility.net"),html);
assert.ok(m.record("page_view",{page:"/meet-brian",channel:"search"}));
assert.ok(m.record("cta_click",{page:"/meet-brian",target:"ai_twin"}));
assert.ok(m.record("outcome",{target:"crm_intake_ack"}));
assert.ok(m.record("voice_connected",{page:"/ask-brian"}));
assert.equal(m.record("voice_connected",{page:"/private-report"}),false);
assert.equal(m.record("outcome",{target:"purchase"}),false);
const report=m.makeReport(7);
assert.equal(report.counts.pageViews,1);
assert.equal(report.counts.landingPageViews,1);
assert.equal(report.counts.ctaClicks,1);
assert.equal(report.counts.crmIntakeAcknowledged,1);
assert.equal(report.counts.googleVoiceConnectionsReported,1);
assert.equal(report.byPage["/meet-brian"],1);
const raw=fs.readFileSync(path.join(tmp,"site-traffic-aggregates.json"),"utf8");
assert.ok(!/email|127\.0\.0\.1|user-agent/i.test(raw));
fs.rmSync(tmp,{recursive:true,force:true});
console.log("Site traffic aggregation tests passed.");
